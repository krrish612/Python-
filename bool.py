# BOOLEAN VALUES (bool) - Python has only two of them: True and False.
# They are written with a capital first letter and WITHOUT quotes.
#
# DRY RUN
#   Student = True          -> Student now holds the value True
#   print(Student)          -> True
#   print(type(Student))    -> <class 'bool'>
#
# NOTE: 'True' (inside quotes) is just text -> <class 'str'>,
#       while True (no quotes) is the boolean value -> <class 'bool'>.

# Store the boolean value True in the variable "Student".
Student = True

# print() shows the value itself, so this prints: True
print(Student)

# type() shows the data type of the value, so this prints: <class 'bool'>
print(type(Student))


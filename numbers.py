# Python can also be used like a calculator.
# A whole number written on its own (like 10) is called an integer, or "int".

print(10) 
print(5+3)## addition
print(10-4)#subtraction
print(5*4)##multiplication 
print(10/2)##division

# Note: the / operator always gives back a decimal number (a "float"),
# so print(10/2) shows 5.0 instead of 5.


# A variable is a named container that stores a value.
# "Age" stores a number (int) and "Name" stores text (str).
# Note: names are case sensitive, so "Name" and "name" are two different variables.
Age = 20
# The space at the end of 'Krrish ' keeps the output readable when other text follows it.
Name = 'Krrish '

# print() can show several values at once - just separate them with commas.
# Every comma automatically puts one space between the values in the output.
print("My name is ",Name ,"and","I am ",Age,"Old")
